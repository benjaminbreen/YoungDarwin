// What the animals of Floreana do, as data the behaviour brain reads.
//
// Each species has a repertoire: behaviours, each with the need it serves
// (`drive`), the hours it belongs to, how it moves (`move`), the rig action it
// shows (`action`), who it involves (`partner`), and the sentence Darwin's
// notebook records when he watches it through (`note`). Responses map signals
// from other animals (a chase, a challenge, a finch hopping up to a tortoise)
// to behaviours; `predators` lists who it fears and how far off.
//
// The behaviours are the ones a patient observer on the island would see,
// and most of the interesting ones need two animals: finches gleaning ticks
// from a tortoise that rises on its legs for them, lava lizards answering one
// another's push-ups, a mockingbird walking up to a man who keeps still.
// Nothing here is scripted as a sequence; the chains come from animals
// answering each other.
//
// Move kinds (see behaviorBrain):
//   stay        hold position; `face` partner or player if set
//   toPlant     walk to a nearby plant, then act there
//   approach    walk to the partner until within `reach`, then act
//   chase       run at the partner, which is sent `chased`
//   retreat     move away from the signal's sender
//   follow      walk toward the nearest kin until within `reach`
//   shade       walk into the shade of the nearest rock or tree, then act
//   stalk       creep to `strikeRange` of the partner, then dash and strike
//
// Partner kinds: 'kin' (same species), 'kinGroup' (catalog kin group),
// 'species' (`species` list), 'player'.

