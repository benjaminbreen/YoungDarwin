function sunPortal({ id, position, normal, width, height, diffuse, intensity, distance = 9, angle = 0.6, shaft = null, bounce = null, castShadow = false, color = '#cfdad8' }) {
  return {
    id,
    position,
    normal,
    width,
    height,
    diffuseIntensity: diffuse,
    color,
    goldenColor: '#f2bf72',
    direct: {
      intensity,
      diffuseProjectorShare: 0.44,
      diffuseProjectorIntensity: intensity * 0.09,
      warmth: 0.5,
      sourceDistance: 1.5,
      distance,
      angle,
      penumbraClear: 0.32,
      penumbraOvercast: 0.7,
      decay: 1.22,
      diffuseCut: 0.16,
      castShadow,
      ...(castShadow ? { shadowMapSize: 1024, shadowRadiusClear: 0.4, shadowRadiusOvercast: 2.0 } : {}),
      ...(shaft ? { shaft } : {}),
    },
    ...(bounce ? { bounce } : {}),
  };
}

